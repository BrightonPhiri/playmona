  var listeners = [];
  var currentLang = 'en';

  FF.i18n = {
    languages: LANGUAGES,

    init: function () {
      var saved = (FF.Storage && FF.Storage.get('language', null));
      if (!saved) {
        var nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
        if (TRANSLATIONS[nav]) saved = nav;
        else saved = 'en';
      }
      this.setLang(saved, true);
    },

    getLang: function () {
      return currentLang;
    },

    getLangInfo: function () {
      for (var i = 0; i < LANGUAGES.length; i++) {
        if (LANGUAGES[i].code === currentLang) return LANGUAGES[i];
      }
      return LANGUAGES[0];
    },

    setLang: function (lang, silent) {
      if (!TRANSLATIONS[lang]) lang = 'en';
      currentLang = lang;
      if (FF.Storage) FF.Storage.set('language', lang);
      if (document && document.documentElement) {
        document.documentElement.setAttribute('lang', lang);
      }
      if (!silent) {
        listeners.slice().forEach(function (fn) {
          try { fn(lang); } catch (e) { if (window.console) console.error(e); }
        });
      }
    },

    onChange: function (cb) {
      listeners.push(cb);
      return function () {
        var idx = listeners.indexOf(cb);
        if (idx !== -1) listeners.splice(idx, 1);
      };
    },

    t: function (key, fallback, vars) {
      var dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
      var str = dict[key] != null ? dict[key] : (TRANSLATIONS.en[key] != null ? TRANSLATIONS.en[key] : fallback || key);
      if (vars && typeof vars === 'object') {
        Object.keys(vars).forEach(function (k) {
          str = str.split('{' + k + '}').join(vars[k]);
        });
      }
      return str;
    }
  };

  // Convenient top-level shorthand
  FF.t = function (key, fallback, vars) {
    return FF.i18n.t(key, fallback, vars);
  };
