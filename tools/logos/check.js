'use strict';
/* Checks the Logo Rush logo files, and installs staged downloads.

     node tools/logos/check.js                          check what is installed
     node tools/logos/check.js --from <stage> --install  check staged files, copy them into
                                                         assets/images/games/logoRush/, merge their
                                                         sources into tools/logos/sources.json

   Both regenerate js/data/logoFiles.js (brand id -> [symbol ext, full ext], '' when
   missing) from the files on disk. Exit 1 when anything is wrong. */

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { cleanSvg } = require('./clean.js');

const ROOT = path.resolve(__dirname, '..', '..');
const DIR = path.join(ROOT, 'assets', 'images', 'games', 'logoRush');
const SOURCES = path.join(__dirname, 'sources.json');
const MAP = path.join(ROOT, 'js', 'data', 'logoFiles.js');
const CAP = { symbol: 60 * 1024, full: 120 * 1024 };
const EXTS = ['svg', 'webp'];

function brands() {
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext('var window = this.window; window.FF = {}; var FF = window.FF;' + fs.readFileSync(path.join(ROOT, 'js/data/logos.js'), 'utf8'), ctx);
  return ctx.window.FF.data.logos.brands;
}

function extOf(dir, name) {
  return EXTS.find((e) => fs.existsSync(path.join(dir, name + '.' + e))) || '';
}

/* Problems with one file (empty when fine). */
function checkFile(p, kind) {
  const out = [];
  const size = fs.statSync(p).size;
  if (size > CAP[kind]) out.push(path.basename(p) + ' is ' + size + ' bytes (cap ' + CAP[kind] + ')');
  if (p.endsWith('.svg')) {
    const s = fs.readFileSync(p, 'utf8');
    if (/<script|<foreignObject|\son\w+\s*=|href\s*=\s*["']https?:/i.test(s)) out.push(path.basename(p) + ' has unsafe markup');
    if (!/viewBox=/.test(s)) out.push(path.basename(p) + ' has no viewBox');
    if (kind === 'symbol' && /<text[\s>]/i.test(s)) out.push(path.basename(p) + ' has text');
  }
  return out;
}

function checkAll(dir) {
  const problems = [];
  brands().forEach((b) => {
    const s = extOf(dir, b.id);
    const f = extOf(dir, b.id + '-full');
    if (!s && !(b.crop && f)) problems.push(b.id + ': no symbol' + (b.crop ? ' and no full logo to crop' : ''));
    if (s) problems.push.apply(problems, checkFile(path.join(dir, b.id + '.' + s), 'symbol'));
    if (f) problems.push.apply(problems, checkFile(path.join(dir, b.id + '-full.' + f), 'full'));
  });
  return problems;
}

function writeMap(dir) {
  const map = {};
  brands().forEach((b) => { map[b.id] = [extOf(dir, b.id), extOf(dir, b.id + '-full')]; });
  const body = Object.keys(map).map((id) => '    ' + JSON.stringify(id) + ': ' + JSON.stringify(map[id])).join(',\n');
  fs.writeFileSync(MAP, '/* PLAYMONA — data/logoFiles.js\n   Generated by `node tools/logos/check.js`: which logo files each Logo Rush brand has\n' +
    '   in assets/images/games/logoRush/ — [symbol extension, full logo extension], \'\' when missing.\n   Classic script, ES5. */\n' +
    'window.FF = window.FF || {};\nFF.data = FF.data || {};\nFF.data.logoFiles = {\n' + body + '\n};\n');
}

function install(stage) {
  const staged = JSON.parse(fs.readFileSync(path.join(stage, 'sources.json'), 'utf8'));
  const sources = fs.existsSync(SOURCES) ? JSON.parse(fs.readFileSync(SOURCES, 'utf8')) : {};
  fs.mkdirSync(DIR, { recursive: true });
  const refused = [];
  brands().forEach((b) => {
    const e = staged[b.id];
    if (!e) return;
    [['symbol', b.id], ['full', b.id + '-full']].forEach(([kind, name]) => {
      if (!e[kind]) return;
      const ext = extOf(stage, name);
      if (!ext) return;
      let src = path.join(stage, name + '.' + ext);
      if (ext === 'svg') {   // clean again: the stage is downloaded data
        const c = cleanSvg(fs.readFileSync(src, 'utf8'));
        fs.writeFileSync(src, c.svg);
      }
      const bad = checkFile(src, kind);
      if (bad.length) { refused.push.apply(refused, bad); return; }
      EXTS.forEach((x) => { const old = path.join(DIR, name + '.' + x); if (fs.existsSync(old)) fs.unlinkSync(old); });
      fs.copyFileSync(src, path.join(DIR, name + '.' + ext));
      sources[b.id] = sources[b.id] || {};
      sources[b.id][kind] = { url: e[kind].url, from: e[kind].from, licence: e[kind].licence };
    });
  });
  const sorted = {};
  Object.keys(sources).sort().forEach((k) => { sorted[k] = sources[k]; });
  fs.writeFileSync(SOURCES, JSON.stringify(sorted, null, 1) + '\n');
  return refused;
}

if (require.main === module) {
  const a = process.argv.slice(2);
  const from = a.indexOf('--from') !== -1 ? a[a.indexOf('--from') + 1] : null;
  let problems = [];
  if (from && a.indexOf('--install') !== -1) {
    const refused = install(path.resolve(from));
    if (refused.length) console.log('not installed:\n  ' + refused.join('\n  '));
  }
  writeMap(DIR);
  problems = checkAll(DIR);
  console.log(problems.length ? problems.length + ' problems:\n  ' + problems.join('\n  ') : 'All logo files are fine.');
  process.exit(problems.length ? 1 : 0);
}

module.exports = { checkAll, checkFile, writeMap, install };
