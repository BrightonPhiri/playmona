#!/usr/bin/env node
/* Writes js/data/sketchFiles.js: the SketchBack objects whose sketch
   (assets/images/sketchback/<id>.webp) exists, in library order. Run it
   after tools/cut-art-sheets.py sketchBack. The game lists itself only
   once enough sketches are in (js/games/sketchBack.js). */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'js', 'data', 'sketchFiles.js');
const DIR = path.join(ROOT, 'assets', 'images', 'sketchback');

function library() {
  const src = fs.readFileSync(path.join(ROOT, 'js', 'data', 'sketches.js'), 'utf8');
  const ids = [];
  const re = /\bo\('([A-Za-z0-9]+)'/g;
  let m;
  while ((m = re.exec(src))) ids.push(m[1]);
  return ids;
}

function list() {
  return library().filter((id) => fs.existsSync(path.join(DIR, id + '.webp')));
}

function write() {
  const ids = list();
  const body = '/* Generated by tools/sketchback/gen-files.js: SketchBack objects that have a sketch. Do not edit. */\n' +
    'window.FF = window.FF || {};\n' +
    'FF.SketchFiles = { ids: ' + JSON.stringify(ids) + ' };\n';
  fs.writeFileSync(OUT, body);
  return ids;
}

module.exports = { list, write };
if (require.main === module) console.log(write().length + ' sketches listed in js/data/sketchFiles.js');
