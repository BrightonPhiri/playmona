'use strict';
/* ============================================================
   PLAYMONA — gen-quizbank.js
   Builds js/data/quizbank.js, the big question bank Quiz Mix loads
   on demand, from Open Trivia DB downloads (opentdb.com, CC BY-SA 4.0).

   Input: one or more folders of opentdb-<category>.json files, each
   { category, results: [...] } as the API returns them with
   encode=url3986. The naughty-words package (LDNOOBW, CC-BY-4.0)
   filters rude questions.

   Usage:
     node tools/gen-quizbank.js <naughty-words en.json> <dir> [<dir> ...]
   ============================================================ */
const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
if (args.length < 2) { console.error('usage: node tools/gen-quizbank.js <naughty en.json> <dir> [<dir> ...]'); process.exit(1); }
const dest = path.join(__dirname, '..', 'js', 'data', 'quizbank.js');

// Open Trivia DB category id -> Quiz Mix topic (null = left out: politics, celebrity gossip).
const TOPIC = {
  9: 'general', 10: 'books', 11: 'screen', 12: 'music', 13: 'music', 14: 'screen',
  15: 'games', 16: 'games', 17: 'science', 18: 'tech', 19: 'tech', 20: 'art',
  21: 'sport', 22: 'geography', 23: 'history', 24: null, 25: 'art', 26: null,
  27: 'animals', 28: 'general', 29: 'games', 30: 'tech', 31: 'games', 32: 'games'
};
const DIFF = { easy: 'e', medium: 'n', hard: 'h' };
// Topics a family quiz should skip, on top of the rude-word list.
const ADULT = /\b(sex|sexual|sexy|porn\w*|suicide|rape\w*|cocaine|heroin|marijuana|cannabis|stripper|prostitut\w*|genital\w*|erotic\w*|nude|naked|masturbat\w*|orgasm\w*|condom\w*|viagra|playboy|brothel|hooker|drunk\w*|nazi\w*)\b/i;
const SHUFFLE_BREAKERS = /\b(all|none|both) of (the )?(above|these|them)\b|\babove\b/i;

const bad = JSON.parse(fs.readFileSync(args[0], 'utf8')).filter((w) => /^[a-z]+$/.test(w));
const badRe = new RegExp('\\b(' + bad.join('|') + ')\\b', 'i');

function decode(s) { try { return decodeURIComponent(s); } catch (e) { return s; } }
function clean(s) { return decode(String(s)).replace(/\s+/g, ' ').trim(); }

const seen = new Set();
const items = [];
const dropped = { dupe: 0, rude: 0, long: 0, breaker: 0, topic: 0 };
const perTopic = {};

args.slice(1).forEach((dir) => {
  fs.readdirSync(dir).filter((f) => /^opentdb-\d+\.json$/.test(f)).sort().forEach((f) => {
    const id = Number(f.match(/\d+/)[0]);
    const topic = TOPIC[id];
    const data = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    (data.results || []).forEach((r) => {
      if (!topic) { dropped.topic++; return; }
      const q = clean(r.question);
      const correct = clean(r.correct_answer);
      const wrong = (r.incorrect_answers || []).map(clean);
      const key = q.toLowerCase();
      if (seen.has(key)) { dropped.dupe++; return; }
      const text = [q, correct].concat(wrong).join(' ');
      if (badRe.test(text) || ADULT.test(text)) { dropped.rude++; return; }
      if (q.length > 220 || [correct].concat(wrong).some((o) => o.length > 80)) { dropped.long++; return; }
      const tf = r.type === 'boolean';
      if (!tf && (wrong.length !== 3 || [correct].concat(wrong).some((o) => SHUFFLE_BREAKERS.test(o)))) { dropped.breaker++; return; }
      if (!tf && new Set([correct].concat(wrong).map((o) => o.toLowerCase())).size !== 4) { dropped.breaker++; return; }
      seen.add(key);
      const row = tf ? [q, [correct], DIFF[r.difficulty] || 'n', topic, 1] : [q, [correct].concat(wrong), DIFF[r.difficulty] || 'n', topic];
      items.push(row);
      perTopic[topic] = (perTopic[topic] || 0) + 1;
    });
  });
});

const out = [
  '/* ============================================================',
  '   PLAYMONA — quizbank.js (generated by tools/gen-quizbank.js; do not edit)',
  '   ' + items.length.toLocaleString('en') + ' quiz questions from the Open Trivia Database',
  '   (https://opentdb.com), licensed CC BY-SA 4.0. This file is shared under',
  '   the same licence. Rows: [question, [correct, wrong…], difficulty e|n|h,',
  '   topic, 1 if true-or-false]. Loaded on demand by js/games/quizMix.js.',
  '   ============================================================ */',
  'window.FF = window.FF || {};',
  'FF.QuizBankData = {',
  '  version: 1,',
  "  source: 'Open Trivia Database (opentdb.com), CC BY-SA 4.0',",
  '  items: ' + JSON.stringify(items),
  '};',
  ''
].join('\n');
fs.writeFileSync(dest, out);
console.log('questions', items.length, 'bytes', Buffer.byteLength(out));
console.log('per topic', JSON.stringify(perTopic));
console.log('dropped', JSON.stringify(dropped));
