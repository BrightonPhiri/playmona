/* Family Fun — asset manifest generator.
   Lists the optional artwork that actually exists so the app never
   requests a missing file (each miss was a 404 on every render).
   Run after adding or removing art:  node tools/gen-asset-manifest.js
*/
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const FOLDERS = ['covers', 'categories', 'ui'];
const out = {};

FOLDERS.forEach(function (folder) {
  const dir = path.join(ROOT, 'assets', 'images', folder);
  out[folder] = {};
  if (!fs.existsSync(dir)) return;
  fs.readdirSync(dir).filter(function (f) { return /\.webp$/i.test(f); }).sort().forEach(function (f) {
    out[folder][f.replace(/\.webp$/i, '')] = 1;
  });
});

const body = '/* Generated by tools/gen-asset-manifest.js — do not edit by hand. */\n' +
  'window.FF = window.FF || {};\n' +
  'FF.AssetManifest = ' + JSON.stringify(out, null, 2) + ';\n';
fs.writeFileSync(path.join(ROOT, 'js', 'data', 'assetManifest.js'), body);
FOLDERS.forEach(function (f) { console.log(f + ': ' + Object.keys(out[f]).length); });
