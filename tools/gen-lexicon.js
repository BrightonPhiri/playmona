'use strict';
/* ============================================================
   PLAYMONA — gen-lexicon.js
   Builds js/data/lexicon.js, the shared English word bank that
   FF.Words (js/words.js) loads for every word game.

   Sources (both free, fetched with npm pack, never shipped as-is):
   - SCOWL via the wordlist-english package (MIT-style SCOWL
     licence, see CREDITS.md). American + British + shared words,
     levels 10–70, so "colour" and "color" both count.
   - LDNOOBW via the naughty-words package (CC-BY-4.0): rude words
     are removed. A few have an everyday meaning (ass, cock, tit,
     suck…): those stay "quiet" - accepted when typed, but never
     dealt as letters, shown as a missed word or put on the TV.

   Usage:
     mkdir <dir> && cd <dir>
     npm pack wordlist-english@1.2.1 naughty-words@1.2.0
     (extract each .tgz into a folder named after it)
     node tools/gen-lexicon.js <dir>
   ============================================================ */
const fs = require('fs');
const path = require('path');

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/gen-lexicon.js <dir with the extracted packages>'); process.exit(1); }
const scowl = path.join(dir, 'wordlist-english-1.2.1', 'package');
const naughty = path.join(dir, 'naughty-words-1.2.0', 'package', 'en.json');
const dest = path.join(__dirname, '..', 'js', 'data', 'lexicon.js');

// Tier 1 everyday, 2 common, 3 known, 4 rare. Games pick from the low tiers
// and accept all of them.
const TIERS = [[10, 20], [35, 40], [50, 55, 60], [70]];
const DIALECTS = ['english', 'american', 'british'];
const MIN = 3;
const MAX = 15;

// Rude-list words with an innocent meaning: accepted when typed, never shown.
const QUIET = ('ass asses butt butts cock cocks tit tits suck sucks snatch snatches escort escorts escorted escorting ' +
  'bareback domination fingering shrimping snowballing pegging spunk spunky nipple nipples undressing ' +
  'hump humps humping humped bondage sex sexes sexed sexual sexually sexuality erotic nude nudes nudity kinky ' +
  'horny genitals rectum anus semen intercourse bitch bitches').split(' ');

function isRude(word, bad) {
  if (bad.has(word)) return true;
  // Plurals of short words only: "butt" must not take "butter" with it.
  if (word.endsWith('s') && bad.has(word.slice(0, -1))) return true;
  if (word.endsWith('es') && bad.has(word.slice(0, -2))) return true;
  // Longer words: anything built on them (orgasmic, whorehouse).
  for (let n = 5; n < word.length; n++) {
    if (bad.has(word.slice(0, n))) return true;
  }
  return false;
}

// Front coding: each word is an upper-case letter (A = 0 … P = 15) giving how
// many letters it shares with the word before, then the rest of it in lower case.
function encode(sorted) {
  let prev = '';
  let out = '';
  for (const w of sorted) {
    let p = 0;
    while (p < prev.length && p < w.length && p < 15 && prev.charCodeAt(p) === w.charCodeAt(p)) p++;
    out += String.fromCharCode(65 + p) + w.slice(p);
    prev = w;
  }
  return out;
}

const bad = new Set(JSON.parse(fs.readFileSync(naughty, 'utf8')).filter((w) => /^[a-z]+$/.test(w)));
const quiet = new Set(QUIET);
const seen = new Set();
const tiers = TIERS.map(() => []);
const quietOut = [];
let rude = 0;

TIERS.forEach((levels, t) => {
  levels.forEach((lvl) => {
    DIALECTS.forEach((d) => {
      const list = JSON.parse(fs.readFileSync(path.join(scowl, d + '-words-' + lvl + '.json'), 'utf8'));
      list.forEach((w) => {
        if (!/^[a-z]+$/.test(w) || w.length < MIN || w.length > MAX || seen.has(w)) return;
        seen.add(w);
        if (quiet.has(w)) { quietOut.push(w); return; }
        if (isRude(w, bad)) { rude++; return; }
        tiers[t].push(w);
      });
    });
  });
});

tiers.forEach((list) => list.sort());
quietOut.sort();
const count = tiers.reduce((n, l) => n + l.length, 0) + quietOut.length;

const out = [
  '/* ============================================================',
  '   PLAYMONA — lexicon.js (generated by tools/gen-lexicon.js; do not edit)',
  '   ' + count.toLocaleString('en') + ' English words for FF.Words, from SCOWL',
  '   (Copyright 2000-2016 Kevin Atkinson; see CREDITS.md), rude words',
  '   removed using the LDNOOBW list (CC-BY-4.0).',
  '   tiers: 1 everyday, 2 common, 3 known, 4 rare, front-coded (A-P =',
  '   letters shared with the previous word). quiet: accepted, never shown.',
  '   ============================================================ */',
  'window.FF = window.FF || {};',
  'FF.Lexicon = {',
  '  version: 1,',
  '  count: ' + count + ',',
  '  tiers: [',
  tiers.map((l) => "    '" + encode(l) + "'").join(',\n'),
  '  ],',
  "  quiet: '" + quietOut.join(' ') + "'",
  '};',
  'if (FF.Words && FF.Words._attach) FF.Words._attach();',
  ''
].join('\n');

fs.writeFileSync(dest, out);
console.log('tiers', tiers.map((l) => l.length).join(' / '), 'quiet', quietOut.length, 'rude removed', rude);
console.log('words', count, 'bytes', Buffer.byteLength(out));
